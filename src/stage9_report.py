"""Stage 9: build reports/STAGE_9.md from outputs/duration_table.csv and outputs/duration_family_summary.csv (tables are generated, not typed)."""
import pandas as pd

t = pd.read_csv("outputs/duration_table.csv")
fam = pd.read_csv("outputs/duration_family_summary.csv")
w = t[t.wellbore != "TOTAL"]
tot = t[t.wellbore == "TOTAL"].iloc[0]
phase_cols = [c for c in t.columns if c.startswith("n_") and c != "n_ddrs"]
short = {"n_spud_conductor": "Spud", "n_surface_casing": "SurfCsg", "n_intermediate_drilling": "IntDrill", "n_intermediate_casing": "IntCsg", "n_reservoir_drilling": "ResDrill",
         "n_liner_casing_run": "Liner/Csg", "n_cementing": "Cement", "n_completion": "Compl", "n_panda": "P&A", "n_logging_testing": "Logging", "n_workover": "Workover",
         "n_waiting_downtime": "Waiting", "n_rig_move_setup": "RigMove", "n_unclassified": "Unclass"}
assert set(phase_cols) <= set(short), phase_cols

def num(x, n=0):
    return "" if pd.isna(x) else (f"{x:,.{n}f}" if n else f"{int(x):,}")

dur = []
for r in w.itertuples():
    td = f"{r.td_md_m:,.1f}" if float(r.td_md_m) % 1 else f"{r.td_md_m:,.0f}"
    dur.append(f"| {r.wellbore} | {r.first_ddr} | {r.last_ddr} | {r.n_ddrs} | {td} | {r.td_date} | {r.elapsed_days_to_td:,} | {r.ddrs_to_td} | {'YES' if r.gap_flag else ''} | {'indicative only' if r.indicative_only else ''} |")
drl = []
for r in w.itertuples():
    kp = "" if pd.isna(r.kickoff_depth_proposed_m) else f"{r.kickoff_depth_proposed_m:,.1f}".rstrip("0").rstrip(".")
    drl.append(f"| {r.wellbore} | {r.td_md_m:,.1f}".replace(".0 |", " |") + f" | {kp} | {r.drilled_length_m:,.1f} | {int(r.ddrs_to_td)} | {r.m_per_report_day:,.1f} | {'PROVISIONAL' if r.derived_status.startswith('PROV') else 'TD only'}{', indicative only' if r.indicative_only else ''} |")
ph = []
for r in w.itertuples(index=False):
    ph.append("| " + " | ".join([r.wellbore] + [str(int(getattr(r, c))) for c in phase_cols] + [str(r.n_ddrs)]) + " |")
ph.append("| **TOTAL** | " + " | ".join(str(int(tot[c])) for c in phase_cols) + f" | {int(tot.n_ddrs)} |")
fr = []
for r in fam.itertuples():
    vals = [str(int(getattr(r, "wellbores"))), str(int(r.n_ddrs))] + [str(int(fam.loc[fam.family == r.family, c].iloc[0])) for c in phase_cols]
    fr.append(f"| {'**' + r.family + '**' if r.family == 'TOTAL' else r.family} | " + " | ".join(vals) + " |")
flagged = w[w.gap_flag]
ftxt = "; ".join(f"{r.wellbore} ({r.elapsed_days_to_td:,} elapsed days against {r.ddrs_to_td} DDRs)" for r in flagged.itertuples())
hdr_ph = "| Wellbore | " + " | ".join(short[c] for c in phase_cols) + " | DDRs |\n|---|" + "---|" * (len(phase_cols) + 1)
hdr_f = "| Family | Wellbores | DDRs | " + " | ".join(short[c] for c in phase_cols) + " |\n|---|---|---|" + "---|" * len(phase_cols)

txt = f"""# Stage 9: Duration table

Date: 2026-10-24. Branch: `rerun-2026-10`. Script: `src/stage9_duration.py` (tables here are generated by `src/stage9_report.py`). Outputs: `outputs/duration_table.csv` (26 wellbores plus a totals row), `outputs/duration_family_summary.csv`.

**Status: complete. `drilled_length_m` and `m_per_report_day` are now filled from the AI-PROPOSED kick-off depths (`outputs/kickoff_proposal.csv`) and are PROVISIONAL for the 15 sidetracks until TJ fills the author columns of `outputs/kickoff_signoff.xlsx`.**

Checks on the Stage 8 items before computing (all confirmed present): uniform kick-off rule applied (one row changed, 15/9-F-11 T2 from 257 to 246 m; 15/9-F-1 C unchanged at 1,364 m); cross-paper correction replaced (decision 34 supersedes item 28); `outputs/kickoff_signoff.xlsx` written with 15 rows and 0 author cells filled; `inputs/paper2_rebuild_prompt_pack_v2.md` copied, SHA-256 identical to the source.

## Definitions

- **First DDR:** earliest report date after excluding the 1980-01-01 sentinel record (one record, `15_9_19_A_1980_01_01.xml`). Only 15/9-19 A is affected: its first DDR is 1997-07-25. **Last DDR:** latest report date.
- **DDRs:** all DDRs of the wellbore, the sentinel included (19 A has 110, of which 109 are genuine), so the per-phase counts add up to 1,759 and Table 2.
- **TD:** the maximum valid measured depth (placeholders `-999.99` and `0` ignored), the same WITSML TD compared with NOD in Stage 7. **TD date:** first date on which a valid depth equals it.
- **Elapsed days to TD:** TD date minus first DDR date, calendar days. **DDRs to TD:** number of DDRs dated from the first DDR to the TD date, inclusive.
- **Gap flag:** YES where elapsed days exceed twice the DDRs to TD, meaning the reports to TD have gaps (TJ's rule; no other gap measure is used).
- **Phase counts:** DDRs per v3 phase, so they are report-days in a phase, not elapsed time. Gaps between reports are not allocated to phases.
- No duration is summed or averaged anywhere, in the totals row or the family summary.

## Durations (26 wellbores)

| Wellbore | First DDR | Last DDR | DDRs | TD (m) | TD date | Elapsed days to TD | DDRs to TD | Gap flag | Note |
|---|---|---|---|---|---|---|---|---|---|
{chr(10).join(dur)}

Gap-flagged ({len(flagged)} of 26): {ftxt}. 19 S has a reporting gap inside its short campaign; F-1, F-4, F-5, F-9, F-14 and F-15 reach their recorded TD after long breaks in reporting, which is the structure already seen as the 730-day strata in Stage 6. For F-1 the TD of 3,632 m is reached in the 2013 re-entry (2013-08-17), 2,085 days after its first DDR (2007-12-02). For F-9 the 1,085 m depth is the same top-hole depth as F-7 and is reached in August 2008 after 275 elapsed days.

Indicative only (TJ): 15/9-19 B (3,272 m is the TD of an abandoned parent leg; NOD's 19 B record matches 19 BT2) and 15/9-F-11 (347 m is a pre-sidetrack stub; NOD's F-11 record matches F-11 T2). Other TD notes: 19 S, the archive ends before its final drilling (WITSML 3,353 m, NOD 3,580 m); F-15, WITSML 4,090 m against NOD 4,105 m. The TD of 15/9-F-11 T2 is 4,562.1 m, reached 2013-05-05.

## Drilled length and metres per report-day (PROVISIONAL for sidetracks)

`drilled_length_m` = TD minus the proposed kick-off depth for the 15 sidetracks; = TD for the 11 original wellbores. `m_per_report_day` = drilled length divided by DDRs to TD. The 15 sidetrack values depend on the AI-proposed kick-off depths and are **PROVISIONAL** until the author columns are filled; the 11 original-wellbore values do not use any kick-off depth.

| Wellbore | TD (m) | Proposed kick-off (m) | Drilled length (m) | DDRs to TD | m per report-day | Status |
|---|---|---|---|---|---|---|
{chr(10).join(drl)}

Caveats: 19 B and F-11 are indicative only (see above). F-1's 31 DDRs to TD mix 4 reports from 2007 (maximum valid depth 226 m) with the 2013 re-entry reports, so its figure of metres per report-day is not a single-campaign rate. Wellbores with the gap flag have a report-day denominator that is much smaller than the elapsed time. These are DDR-count rates, not elapsed-time rates.

## DDRs per phase, per wellbore

{hdr_ph}
{chr(10).join(ph)}

Check: each row sums to its DDR count (asserted in the script); the totals row equals Table 2 (256 Reservoir drilling, 228 Completion, 144 Liner/Casing, 120 Waiting, 100 Cementing, 93 Logging, 82 Intermediate casing, 77 Intermediate drilling, 66 Surface casing, 52 Spud, 41 P&A, 38 Rig move, 6 Workover, 456 Unclassified; 1,303 classified; 1,759 total).

## Well-family summary (wellbores, DDRs and phase counts only)

{hdr_f}
{chr(10).join(fr)}

11 families, 26 wellbores, 1,759 DDRs; the 19 series has 5 wellbores and 375 DDRs.

## Caveats for the paper

- The phase counts inherit the classifier's limits: 456 of 1,759 DDRs (25.9%) are Unclassified, and 339 of the 1,421 DDRs with a usable depth.
- "Days to TD" is a property of the archive: wellbores with long reporting gaps (the seven flagged) cannot be read as drilling durations without the DDRs-to-TD column next to them.
- TD is the maximum depth in the archive, not the NOD final depth; for 19 S the archive ends before final drilling.
"""
open("reports/STAGE_9.md", "w", encoding="utf-8").write(txt)
print(len(txt), "| flagged:", len(flagged))
