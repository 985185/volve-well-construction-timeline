"""Stage 4d: paper-ready priority order and hole-size rules, generated from the frozen PHASES_V3 (open item 3)."""
import re, sys
import pandas as pd
sys.path.insert(0, "src")
import classifier_v3 as C

d = pd.read_parquet("data/interim/ddr.parquet")
txt = d.sum24Hr.fillna("").map(lambda t: C.normalise_text(t.strip()).lower())
hits = {name: txt.map(lambda t, rx=re.compile("|".join(p), re.I): bool(rx.search(t))) for name, _, p in C.PHASES_V3}
H = pd.DataFrame(hits)
final = pd.read_parquet("data/interim/classified_new.parquet").phase
nmatch = H.sum(axis=1)
print("DDRs matching 0 / 1 / 2 / 3+ phases:", int((nmatch == 0).sum()), int((nmatch == 1).sum()), int((nmatch == 2).sum()), int((nmatch >= 3).sum()))
size_rx = re.compile(r"\d")
is_size = lambda p: bool(size_rx.search(re.sub(r"\{\d+(?:,\d*)?\}", "", p)))  # size-based = a digit outside {m,n} quantifiers (hole, casing or liner size)
rows = []
for name, pri, pats in C.PHASES_V3:
    size = [p for p in pats if is_size(p)]
    rows.append({"priority": pri, "phase": name, "n_patterns": len(pats), "n_size_patterns": len(size),
                 "ddrs_matching_any_pattern": int(H[name].sum()), "ddrs_assigned": int((final == name).sum()),
                 "assigned_to_higher_priority_phase_instead": int(H[name].sum()) - int((final == name).sum()),
                 "size_patterns": "; ".join(size), "keyword_patterns": "; ".join(p for p in pats if p not in size)})
R = pd.DataFrame(rows); R.to_csv("outputs/stage4_priority_rules.csv", index=False)
esc = lambda s: s.replace("|", "\|")
with open("outputs/stage4_priority_rules.md", "w", encoding="utf-8") as f:
    f.write("# Classifier v3: priority order and pattern rules\n\nGenerated by `src/stage4_rules_table.py` from `src/classifier_v3.py` (frozen). Rule: all 13 phases are tested on the lower-cased, fraction-normalised narrative; a phase matches if any of its regular expressions is found anywhere (`re.search`, case-insensitive); the matching phase with the lowest priority number is assigned; no match gives Unclassified. Hole and casing sizes are written as digits with `.` wildcards for the fraction separator (for example `17.{0,3}1.2` matches 17 1/2).\n\n")
    f.write("| Priority | Phase | Size-based patterns (hole, casing, liner sizes) | Keyword patterns | DDRs matching | DDRs assigned |\n|---|---|---|---|---|---|\n")
    for r in rows:
        f.write(f"| {r['priority']} | {r['phase']} | " + (", ".join(f"`{esc(p)}`" for p in r["size_patterns"].split("; ")) if r["size_patterns"] else "none") + " | " + (", ".join(f"`{esc(p)}`" for p in r["keyword_patterns"].split("; ")) if r["keyword_patterns"] else "none") + f" | {r['ddrs_matching_any_pattern']} | {r['ddrs_assigned']} |\n")
print(R[["priority", "phase", "n_patterns", "n_size_patterns", "ddrs_matching_any_pattern", "ddrs_assigned", "assigned_to_higher_priority_phase_instead"]].to_string(index=False))
print("sum matching:", int(R.ddrs_matching_any_pattern.sum()), "sum assigned:", int(R.ddrs_assigned.sum()))
# winners over losers among multi-match DDRs
pairs = {}
for i in H.index[nmatch >= 2]:
    ph = [n for n, _, _ in C.PHASES_V3 if H.loc[i, n]]
    for l in ph[1:]: pairs[(ph[0], l)] = pairs.get((ph[0], l), 0) + 1
print("top winner>loser pairs:", sorted(pairs.items(), key=lambda kv: -kv[1])[:8])
# the suspected dead 8½ pattern: does it ever match after normalisation?
dead = re.compile(r"8½.{0,5}(?:hole|section)", re.I)
print("8½ pattern matches on normalised text:", int(txt.map(lambda t: bool(dead.search(t))).sum()))
